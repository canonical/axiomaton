//go:build unix

package proxy

import (
	"os"
	"path/filepath"
	"syscall"
)

// lockFile takes an exclusive advisory lock on path, creating it as
// needed, and blocks until it is held. Several ax processes share the cache
// and CA directories, and this is how they take turns downloading the same
// file, refreshing the same git mirror or creating the CA. The returned
// function releases the lock.
func lockFile(path string) (func(), error) {
	if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
		return nil, err
	}
	f, err := os.OpenFile(path, os.O_CREATE|os.O_RDWR, 0o644)
	if err != nil {
		return nil, err
	}
	if err := syscall.Flock(int(f.Fd()), syscall.LOCK_EX); err != nil {
		f.Close()
		return nil, err
	}
	return func() {
		syscall.Flock(int(f.Fd()), syscall.LOCK_UN)
		f.Close()
	}, nil
}
